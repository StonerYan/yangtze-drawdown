"""Fact sheet: formatted numbers used in the revised text (read from out/*.json)."""
import json, os, numpy as np, pandas as pd
O = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results")
J = lambda n: json.load(open(f"{O}/{n}.json", encoding="utf-8"))
r1, r2, r3, r5, r6, r7 = J("r1_core"), J("r2_longrecord"), J("r3_exposure"), J("r5_spatial"), J("r6_misc"), J("r7_bands")
f = lambda x, d=1: f"{x:.{d}f}".replace("-", "−")
ci = lambda b, d=1: f"{f(b['mean'], d)} ({f(b['lo'], d)} to {f(b['hi'], d)})"
print("=== A headline ===")
for k in ("n74", "n71", "n3"):
    a = r1["A"][k]; print(k, "n", a["n"])
    for v in "SRG": print("  ", v, ci(a[v]), "median", f(a[v]["median"]), "| subbasin", a[v]["sub_basin_ci"] and [f(x) for x in a[v]["sub_basin_ci"]], "| grid3", a[v]["grid3_ci"] and [f(x) for x in a[v]["grid3_ci"]])
    print("   gap", ci(a["gap_R_minus_S"]), "median", f(a["gap_R_minus_S"]["median"]), "| G<0", a["n_G_neg"], "S<0", a["n_S_neg"], "R<0", a["n_R_neg"], "G<0&S>=0", a["n_G_neg_S_nonneg"])
print("G vs S-R", r1["G_vs_S_minus_R_74"])
print("subbasin RE 71:", {v: [f(r1["subbasin_RE_71"][v][k], 2) for k in ("mu", "lo", "hi", "I2")] for v in "SRG"})
print("=== B sensitivity ===")
for k, v in r1["B"]["refdefs_ci"].items(): print(" refdef", k, "n74", ci(v["n74"]), "n71", ci(v["n71"]))
for k, v in r1["B"]["refdefs"].items(): print("   G", k, "n74", f(v["n74"]["G_" + k]), "n71", f(v["n71"]["G_" + k]))
for k, v in r1["B"]["windows"].items(): print(" window", k, {s: {x: f(v[s][x]["mean"]) for x in "SRG"} for s in v})
print(" LOYO ranges", r1["B"]["loyo_range_n74"], r1["B"]["loyo_range_n71"])
print(" year-block", json.dumps(r1["B"]["year_block"]))
print("=== C ===")
print(" nobs ring", r1["C"]["nobs_ring_by_year"]); print(" nobs shore", r1["C"]["nobs_shore_by_year"]); print(" valid2017", r1["C"]["valid_2017"], r1["C"]["valid_2018_2025"])
print(" density-adj", {k: [f(x, 2) for x in v["raw"]] + [f(x, 2) for x in v["adj"]] for k, v in r1["C"].items() if "density" in k})
for lab, d in r1["C"]["composites"].items(): print(" comp", lab, {s: {x: ci(d[s][x]) for x in "SRG"} for s in d})
print("=== D ===")
for k in ("n_all", "n71"): print(k, json.dumps({a: (round(b, 3) if isinstance(b, float) else b) for a, b in r1["D"][k].items()}))
print(json.dumps(r1["D"]["regression_adjustment"], indent=0))
print("anom 2022", r1["D"]["annual_anomalies"]["S"]["2022"], r1["D"]["annual_anomalies"]["R"]["2022"], r1["D"]["annual_anomalies"]["G"]["2022"])
print("=== R2 ===")
print(" looks", r2["looks_by_year"]); print(" models")
for k, m in r2["models"].items(): print("  ", k, "linear", f(m["linear"]), "hinge", {a: f(b, 1) for a, b in m["hinge"].items()}, "step", {a: f(b) for a, b in m["step"].items()}, "step_ci", {a: [f(x) for x in b] for a, b in m["step_ci"].items()}, "BIC", {a: f(b, 1) for a, b in m["BIC"].items()}, "supF", f(m["supF"]), "p", m["supF_boot_p"])
print(" exclude 2011-14", json.dumps({k: {a: [round(x, 2) for x in b] for a, b in v.items()} for k, v in r2["exclude_2011_2014"].items()}))
print(" single sensor", {k: ci(v) for k, v in r2["single_sensor"].items()})
print(" baci", {k: (f(v["mean"], 3), f(v["lo"], 3), f(v["hi"], 3), v["n"]) for k, v in r2["baci"].items() if k != "n_res"}, r2["baci"]["n_res"])
print(" modis", {k: ci(v) for k, v in r2["modis"].items()}); print(" modis vs s2", r2["modis_vs_s2_R"]); print(" s2 vs landsat", r2["s2_vs_landsat_2018_2025"])
print("=== R3 exposure ===")
print(json.dumps(r3["validation"])); 
for k, v in r3["reg"].items():
    if isinstance(v, dict): print(" ", k, {a: (f(b["beta"], 4), f(b["lo"], 4), f(b["hi"], 4)) for a, b in v.items() if isinstance(b, dict)}, v.get("n_pixel_years"), v.get("n_clusters"), v.get("n_pixels"))
    else: print(" ", k, v)
print(" accounting", r3["accounting"])
print("=== R5 ===")
print(" moran n71", {v: {s: (f(x["I"], 3), x["p"]) for s, x in d.items()} for v, d in r5["moran"]["n71"].items()})
print(" multilevel", {v: {a: (f(b, 2) if isinstance(b, float) else b) for a, b in d.items() if a in ("mu", "lo", "hi", "share_basin", "share_res", "share_win", "n_win")} for v, d in r5["multilevel_71"].items()})
print(" rf", r5["rf_R"], "split", r5["split_half_R"]); print(" frame", json.dumps(r5["frame"], default=float)[:1500])
print(" subbasin corr", {k: (f(v[0], 2), f(v[1], 3)) for k, v in r5["subbasin_corr"].items()})
print("=== R6 ===")
print(" lakes", {v: ci(b) for v, b in r6["lakes"]["mean"].items()}, r6["lakes"]["n_win"], r6["lakes"]["n_R_pos"])
print(" lake sites", {l: {v: (f(b["mean"]), f(b["lo"]), f(b["hi"]), b["n"]) for v, b in d.items()} for l, d in r6["lakes"]["by_lake"].items()})
print(" scenarios", {k: {l: [f(x) for x in v] for l, v in d.items()} for k, d in r6["scenarios"].items()}); print(" effect", r6["effect_size"]); print(" V vs S", r6["V_vs_S"])
print("=== R7 bands ===")
for lab, d in r7.items():
    for lo, b in d.items(): print(lab, lo, "S", ci(b), "R", f(b["R_same_reservoirs"]), "G", ci(b["G"]), "level", f(b["level"], 3), "n", b["n_res"], "share", f(b["pixel_share"], 2))
v = J("vegfrac_thresholds"); print("=== V ===")
for k, b in v.items(): print(k, "n71", ci(b["n71"], 2), "n74", ci(b["n74"], 2), "meanV", f(b["Vmean"], 2))
s = J("sensitivity_variants"); print("=== variants (pixel sensitivity) ===")
for k, d in s.items(): print(k, "n71", {x: ci(d["n71"][x]) for x in "SRG"})
